"""Render the eval-harness JSON results into the auto-managed block of
`docs/benchmarks.md`.

The nightly CI job runs the forecast + anomaly harnesses (which write
`eval/results/*.json`), then runs this to refresh the table between the
AUTO markers and opens a PR if the file changed. Pure functions
(`render`, `splice`) are unit-tested; `main` is the CI glue.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

START = "<!-- BENCHMARKS:AUTO:START -->"
END = "<!-- BENCHMARKS:AUTO:END -->"


def _forecast_table(obj: dict[str, Any]) -> str:
    rows = obj.get("results", [])
    if not rows:
        return "_No forecast results._"
    lines = [
        "| tag | model | n_test | MAE | RMSE | sMAPE |",
        "|-----|-------|-------:|----:|-----:|------:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['tag']} | {r['model']} | {r['n_test']} | "
            f"{r['mae']:.4g} | {r['rmse']:.4g} | {r['smape']:.4g} |"
        )
    skipped = obj.get("skipped") or []
    if skipped:
        lines.append("")
        lines.append(f"_Skipped models: {', '.join(skipped)}._")
    return "\n".join(lines)


def _anomaly_table(rows: list[dict[str, Any]]) -> str:
    if not rows:
        return "_No anomaly results._"
    lines = [
        "| fault | profile | threshold | precision | recall | F1 |",
        "|------:|---------|----------:|----------:|-------:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['fault_id']} | {r['fault_profile']} | "
            f"{r['threshold']:.4g} | {r['precision']:.3f} | "
            f"{r['recall']:.3f} | {r['f1']:.3f} |"
        )
    return "\n".join(lines)


def render(
    forecast_obj: dict[str, Any] | None,
    anomaly_obj: list[dict[str, Any]] | None,
) -> str:
    """The full auto-block body (between, not including, the markers).

    Deliberately timestamp-free: the block is a pure function of the
    harness numbers, so the nightly job's PR only opens when results
    actually move (the commit/PR date carries the "when").
    """
    parts = [
        "_Auto-generated by the nightly eval job (`eval/render_benchmarks.py`)._",
        "",
        "### Forecast",
        "",
        _forecast_table(forecast_obj or {}),
        "",
        "### Anomaly detection",
        "",
        _anomaly_table(anomaly_obj or []),
    ]
    return "\n".join(parts)


def splice(doc: str, block: str) -> str:
    """Replace the content between the AUTO markers (markers preserved).

    Raises if the markers are missing — we never silently append.
    """
    if START not in doc or END not in doc:
        raise ValueError(f"benchmarks doc missing {START} / {END} markers")
    head, rest = doc.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{block}\n{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Render benchmarks into docs/benchmarks.md")
    p.add_argument("--forecast", type=Path, default=Path("eval/results/forecast.json"))
    p.add_argument("--anomaly", type=Path, default=Path("eval/results/anomaly.json"))
    p.add_argument("--doc", type=Path, default=Path("docs/benchmarks.md"))
    args = p.parse_args(argv)

    forecast_obj = (
        json.loads(args.forecast.read_text(encoding="utf-8")) if args.forecast.exists() else None
    )
    anomaly_obj = (
        json.loads(args.anomaly.read_text(encoding="utf-8")) if args.anomaly.exists() else None
    )
    if forecast_obj is None and anomaly_obj is None:
        print("no result files found; nothing to render", file=sys.stderr)
        return 1

    doc = args.doc.read_text(encoding="utf-8")
    updated = splice(doc, render(forecast_obj, anomaly_obj))
    if updated != doc:
        args.doc.write_text(updated, encoding="utf-8")
        print(f"updated {args.doc}")
    else:
        print(f"{args.doc} already current")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
